import assert from 'node:assert/strict';
import {createRun,validateRun,selectActivity,tickRun,rememberStop} from '../js/trip.js';
const initial=createRun(0,'trip-qa-one');assert(validateRun(initial));
let clean=selectActivity(initial,'clean',0);
clean=tickRun(clean,{distance:0},{distance:1001,speed:60,x:0,contact:false,mode:'arcade'},{},1/60);
assert.equal(clean.activity.status,'complete');assert.deepEqual(clean.awards,['clean']);
let reset=selectActivity(initial,'clean',0);
reset=tickRun(reset,{distance:0},{distance:800,speed:60,x:0,contact:true,mode:'arcade'},{},1/60);
assert.equal(reset.activity.progress,0);assert.equal(reset.contacts,1);
reset=tickRun(reset,{distance:800},{distance:1801,speed:60,x:0,contact:false,mode:'arcade'},{},1/60);assert.equal(reset.activity.status,'complete');
let flow=selectActivity(initial,'flow',0);
for(let i=0;i<2701;i++)flow=tickRun(flow,{distance:i},{distance:i+1,speed:65,x:0,contact:false,mode:'arcade'},{},1/60);
assert.equal(flow.activity.status,'complete');assert.deepEqual(flow.awards,['flow']);
flow=selectActivity(initial,'flow',0);
for(let i=0;i<600;i++)flow=tickRun(flow,{distance:i},{distance:i+1,speed:65,x:0,contact:false,mode:'arcade'},{},1/60);
flow=tickRun(flow,{distance:600},{distance:601,speed:130,x:0,contact:false,mode:'arcade'},{},1/60);assert.equal(flow.activity.streak,0);
let explore=selectActivity(initial,'explore',0);
explore=rememberStop(explore,'coast:salmar');explore=rememberStop(explore,'coast:salmar');assert.equal(explore.activity.progress,1);
explore=rememberStop(explore,'coast:faro');explore=rememberStop(explore,'coast:tunel');assert.equal(explore.activity.status,'complete');assert.deepEqual(explore.awards,['explore']);
assert(validateRun(explore));assert.equal(validateRun({...explore,elapsed:Infinity}),null);
const free=tickRun(initial,{distance:0},{distance:5000,speed:80,x:0,contact:false,mode:'cruise'},{},1/60);assert.deepEqual(free.awards,[],'cruise does not impose objectives');
const waiting=tickRun(selectActivity(initial,'clean',0),{distance:0},{distance:5000,speed:80,x:0,contact:false,mode:'cruise'},{},1/60);assert.equal(waiting.activity.progress,0,'selected objective waits during cruise');
console.log('PASS: clean kilometre/contact reset, 45 s flow/speed reset, three unique memories, optional free travel');
