#!/usr/bin/env node
/* Optional classic mirror. The shipped HTTP entry uses native ES modules.
 * Every module keeps its own scope; a concatenation without these closures
 * previously let main.poly replace visuals.poly and crash the first frame.
 * No npm install or build dependency is required.
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {resolve, relative, dirname, sep} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const entry=resolve(root,'js/main.js'), output=resolve(root,'js/game.bundle.js');
const modules=new Map(), visiting=new Set(), order=[];
const moduleId=file=>relative(root,file).split(sep).join('/');
const importPattern=/^\s*import\s+([\s\S]*?)\s+from\s+['"]([^'"]+)['"]\s*;?\s*$/gm;

function visit(file){
 if(modules.has(file))return;
 if(visiting.has(file))throw Error('Circular imports are not supported by this optional builder: '+moduleId(file));
 visiting.add(file);
 const source=readFileSync(file,'utf8');
 const syntax=spawnSync(process.execPath,['--input-type=module','--check'],{input:source,encoding:'utf8'});
 if(syntax.status!==0)throw Error('Syntax error in '+moduleId(file)+'\n'+syntax.stderr);
 const imports=[];
 let body=source.replace(importPattern,(_,bindings,specifier)=>{
  if(!specifier.startsWith('.'))throw Error('Only local modules are supported: '+specifier);
  const dependency=resolve(dirname(file),specifier);
  if(!dependency.startsWith(root+sep))throw Error('Import leaves project: '+specifier);
  visit(dependency);
  imports.push({bindings:bindings.trim(),id:moduleId(dependency)});
  return '';
 });
 body=body.replace(/^\s*import\s+['"]([^'"]+)['"]\s*;?\s*$/gm,(_,specifier)=>{
  if(!specifier.startsWith('.'))throw Error('Only local modules are supported: '+specifier);
  const dependency=resolve(dirname(file),specifier);visit(dependency);return '';
 });
 const exported=[];
 body=body.replace(/\bexport\s+(const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/g,(_,kind,name)=>{exported.push([name,name]);return kind+' '+name});
 body=body.replace(/^\s*export\s*\{([^}]+)\}\s*;?\s*$/gm,(_,names)=>{
  for(const raw of names.split(',')){const pair=raw.trim().split(/\s+as\s+/);exported.push([pair[1]||pair[0],pair[0]])}return '';
 });
 if(/^\s*(?:export|import)\b/m.test(body))throw Error('Unsupported module syntax in '+moduleId(file)+'. Keep using native ESM, or extend the builder explicitly.');
 const localImports=imports.map(({bindings,id})=>{
  if(bindings.startsWith('{'))return 'const '+bindings.replace(/\s+as\s+/g,': ')+' = __modules['+JSON.stringify(id)+'];';
  if(/^\*\s+as\s+\w+$/.test(bindings))return 'const '+bindings.replace(/^\*\s+as\s+/,'')+' = __modules['+JSON.stringify(id)+'];';
  throw Error('Unsupported import binding in '+moduleId(file)+': '+bindings);
 }).join('\n');
 modules.set(file,{source,body,localImports,exported});visiting.delete(file);order.push(file);
}

visit(entry);
const hash=createHash('sha256');for(const file of order)hash.update(moduleId(file)+'\n'+modules.get(file).source+'\n');
const parts=[`/* CHASE-404 optional classic mirror. Generated by tools/build.mjs.\n * Source SHA-256: ${hash.digest('hex')}\n * Native ES modules are the authoritative HTTP entry. Do not edit this file.\n */\n(function(){\n'use strict';\nconst __modules=Object.create(null);`];
for(const file of order){
 const {body,localImports,exported}=modules.get(file);
 const names=exported.map(([publicName,local])=>JSON.stringify(publicName)+': '+local).join(', ');
 parts.push(`\n// ${moduleId(file)}\n__modules[${JSON.stringify(moduleId(file))}]=(()=>{\n${localImports}\n${body.trim()}\nreturn {${names}};\n})();`);
}
parts.push('\n})();\n');const bundle=parts.join('\n');
const check=spawnSync(process.execPath,['--input-type=commonjs','--check'],{input:bundle,encoding:'utf8'});
if(check.status!==0)throw Error('Generated bundle is invalid\n'+check.stderr);
if(process.argv.includes('--check')){
 if(readFileSync(output,'utf8')!==bundle){console.error('FAIL: optional bundle is stale. Run node tools/build.mjs.');process.exitCode=1}
 else console.log('PASS: optional bundle reproduces native modules with isolated scopes ('+order.length+' modules).');
}else{writeFileSync(output,bundle);console.log('Built js/game.bundle.js with '+order.length+' isolated module scopes.');}
